import type { TaskWithRelations, Workflow } from '@sindral/shared';
import { getStateStyle, getStep, isAgentActive } from '@sindral/shared';
import { Markdown } from '@/components/Markdown';
import { Button } from '@/components/Button';
import { ExternalLink } from '@/components/ExternalLink';
import { shortPrLabel } from '@/lib/format';
import { planOverview } from '@/lib/plan';

interface SummaryTabProps {
  task: TaskWithRelations;
  workflow: Workflow | null;
  canApprove: boolean;
  approving: boolean;
  onApprove: () => void;
  onViewPlan: () => void;
}

const PLAN_FIELDS = [
  ['summary', 'Summary'],
  ['assumptions', 'Assumptions'],
] as const;

export function SummaryTab({ task, workflow, canApprove, approving, onApprove, onViewPlan }: SummaryTabProps) {
  const agentActive = isAgentActive(task, workflow);
  const step = workflow ? getStep(workflow, task.currentStepId ?? workflow.entryStepId) : null;
  const style = getStateStyle(task.state, step);
  const overview = task.plan ? planOverview(task.plan) : null;

  return (
    <div className="overflow-y-auto h-full p-6">
      <div className="max-w-4xl space-y-6">
        {agentActive && (
          <div className="flex items-start gap-3 p-4 rounded-lg" style={{ background: '#fbbf2408', border: '1px solid #fbbf2420' }}>
            <span className="w-1.5 h-1.5 rounded-full bg-amber-400 animate-pulse mt-1.5 shrink-0" aria-hidden="true" />
            <div>
              <p className="text-sm font-medium text-amber-200/80">Agent is working</p>
              <p className="text-xs text-muted-foreground mt-0.5 leading-relaxed">
                {task.state === 'troubleshoot'
                  ? 'The troubleshooting agent is diagnosing what went wrong.'
                  : step
                    ? `${step.label} is running on your worker (${style.label}).`
                    : 'An agent is running on your worker.'}
              </p>
            </div>
          </div>
        )}

        <section>
          <p className="text-xs font-semibold uppercase tracking-wider text-muted-foreground mb-2">Description</p>
          {task.description ? (
            <Markdown>{task.description}</Markdown>
          ) : (
            <p className="text-sm text-muted-foreground italic">No description.</p>
          )}
        </section>

        <section>
          <p className="text-xs font-semibold uppercase tracking-wider text-muted-foreground mb-2">Task contract</p>
          <div className="grid gap-3">
            <div className="p-4 rounded-lg bg-muted border border-border min-w-0">
              <p className="text-[10px] font-semibold uppercase tracking-wider text-muted-foreground mb-1.5">Outcome</p>
              {task.outcome ? <Markdown className="text-xs">{task.outcome}</Markdown> : <p className="text-xs text-muted-foreground italic">Will be generated by the first agent.</p>}
            </div>
            <div className="p-4 rounded-lg bg-muted border border-border min-w-0">
              <p className="text-[10px] font-semibold uppercase tracking-wider text-muted-foreground mb-1.5">Acceptance criteria</p>
              {task.acceptanceCriteria ? (
                <Markdown className="text-xs">{task.acceptanceCriteria}</Markdown>
              ) : (
                <p className="text-xs text-muted-foreground italic">Will be generated by the first agent.</p>
              )}
            </div>
          </div>
        </section>

        {task.repos.length > 0 && (
          <section>
            <p className="text-xs font-semibold uppercase tracking-wider text-muted-foreground mb-2">Repositories</p>
            <div className="flex flex-wrap gap-1.5">
              {task.repos.map((r) => (
                <span key={r} className="text-[11px] font-mono px-2 py-1 rounded bg-secondary border border-border text-secondary-foreground">
                  {r}
                </span>
              ))}
            </div>
          </section>
        )}

        {task.plan && (
          <section>
            <div className="flex items-center justify-between gap-4 mb-3">
              <p className="text-xs font-semibold uppercase tracking-wider text-muted-foreground">Plan at a glance</p>
              <button type="button" onClick={onViewPlan} className="text-xs text-accent hover:text-accent/70 transition-colors">
                View full plan →
              </button>
            </div>
            <div className="grid gap-3">
              {PLAN_FIELDS.map(([key, label]) => (
                <div key={key} className="p-4 rounded-lg bg-muted border border-border min-w-0">
                  <p className="text-[10px] font-semibold uppercase tracking-wider text-muted-foreground mb-1.5">{label}</p>
                  <div className="overflow-x-auto">
                    <Markdown className="text-xs [&_table]:min-w-full">{overview?.[key] ?? ''}</Markdown>
                  </div>
                </div>
              ))}
            </div>
            {canApprove && (
              <div className="mt-3 flex justify-end">
                <Button variant="success" onClick={onApprove} disabled={approving}>
                  Approve Plan
                </Button>
              </div>
            )}
          </section>
        )}

        {(task.pullRequests.length > 0 || task.prUrl) && (
          <section>
            <p className="text-xs font-semibold uppercase tracking-wider text-muted-foreground mb-2">Pull Requests</p>
            <div className="space-y-2">
              {(task.pullRequests.length > 0
                ? task.pullRequests
                : [{ id: 'legacy', repository: task.repos[0] ?? 'Repository', url: task.prUrl!, status: 'open' as const, branch: task.branch ?? '', baseBranch: task.baseBranch ?? '' }]
              ).map((pr) => (
                <div key={pr.id} className="flex items-center justify-between gap-3 rounded-lg bg-input border border-border px-3 py-2">
                  <div className="min-w-0">
                    <p className="text-[11px] font-mono text-secondary-foreground truncate">{pr.repository}</p>
                    <p className="text-[10px] font-mono text-muted-foreground truncate">
                      {pr.branch}
                      {pr.baseBranch ? ` → ${pr.baseBranch}` : ''}
                    </p>
                  </div>
                  <div className="flex items-center gap-2 shrink-0">
                    <span className="text-[9px] font-mono uppercase text-muted-foreground">{pr.status}</span>
                    <ExternalLink href={pr.url} className="text-xs font-mono text-accent" fallback={<span className="text-xs font-mono text-muted-foreground">{pr.url}</span>}>
                      {shortPrLabel(pr.url)} ↗
                    </ExternalLink>
                  </div>
                </div>
              ))}
            </div>
          </section>
        )}

        {task.state === 'todo' && (
          <div className="p-4 rounded-lg text-sm bg-secondary border border-border">
            <p className="text-secondary-foreground">
              This task is ready to start. Use the action button above to hand it to the first agent.
            </p>
          </div>
        )}

        {!agentActive && step?.type === 'human' && task.state !== 'todo' && (
          <div className="p-4 rounded-lg bg-secondary border border-border">
            <p className="text-sm font-medium text-foreground">Waiting for you</p>
            <p className="text-xs text-muted-foreground mt-0.5 leading-relaxed">
              {step.label}: use the action buttons above, or send chat feedback to request changes.
            </p>
          </div>
        )}

        {task.state === 'failure' && (
          <div className="p-4 rounded-lg" style={{ background: '#f8711808', border: '1px solid #f8711820' }}>
            <p className="text-sm font-medium text-red-300/80 mb-1">Task failed</p>
            <p className="text-xs text-muted-foreground leading-relaxed">
              The agent ran into an error it couldn't resolve. Use the chat to provide guidance, retry the step, or run the troubleshoot agent.
            </p>
            {task.lastError && (
              <pre className="mt-3 text-[11px] font-mono leading-relaxed whitespace-pre-wrap break-words text-red-200/70 bg-background/60 rounded p-3 border border-border max-h-64 overflow-auto">
                {task.lastError}
              </pre>
            )}
          </div>
        )}

        {task.state === 'done' && (
          <div className="p-4 rounded-lg" style={{ background: '#34d39908', border: '1px solid #34d39920' }}>
            <p className="text-sm font-medium text-emerald-300/80">Task complete</p>
            <p className="text-xs text-muted-foreground mt-0.5">All work has been accepted.</p>
          </div>
        )}
      </div>
    </div>
  );
}
