import type { GitRunner } from './git.js';
import type { GitHubFeedbackReference } from '@sindral/shared';
import { run, type RunOptions, type RunResult } from './proc.js';
import type { RepoRef } from './workspace.js';

/** Marker embedded in PR bodies/comments so the server can recognise Sindral's own posts. */
export const SINDRAL_MARKER = '<!-- sindral -->';
export const COMMIT_AUTHOR = 'Sindral AI <sindral@users.noreply.github.com>';
const MAX_PR_SECTION_LENGTH = 5_000;
const TRUNCATION_NOTICE = '\n\n_Section truncated for readability._';

export type GhRunner = (args: readonly string[], opts?: RunOptions) => Promise<RunResult>;

/** Builds a `gh` invoker; the token is passed only to `gh` through `GH_TOKEN`. */
export function ghRunner(ghBin: string, token: string | null): GhRunner {
  return (args, opts = {}) =>
    run(ghBin, args, {
      ...opts,
      env: { GH_PROMPT_DISABLED: '1', GH_NO_UPDATE_NOTIFIER: '1', ...(token ? { GH_TOKEN: token } : {}), ...opts.env },
    });
}

export function prTitle(taskKey: string, taskTitle: string): string {
  const title = taskTitle.trim() || 'Sindral change';
  return `${taskKey}: ${title}`.slice(0, 250);
}

export function prBody(opts: { taskKey: string; motivation?: string; assumptions?: string; summary: string; taskUrl?: string }): string {
  return [
    '## Motivation',
    '',
    prSection(opts.motivation, '_No motivation provided._'),
    '',
    '## Assumptions',
    '',
    prSection(opts.assumptions, '_No additional assumptions were identified._'),
    '',
    '## Outcomes',
    '',
    prSection(opts.summary, '_No outcomes provided._'),
    '',
    `Task ${opts.taskKey}${opts.taskUrl ? ` (${opts.taskUrl})` : ''}`,
    '',
    'Generated by Sindral AI. Comments on this pull request are picked up as feedback.',
    '',
    SINDRAL_MARKER,
  ].join('\n');
}

function prSection(value: string | undefined, fallback: string): string {
  const text = value?.trim() || fallback;
  if (text.length <= MAX_PR_SECTION_LENGTH) return text;
  return `${text.slice(0, MAX_PR_SECTION_LENGTH - TRUNCATION_NOTICE.length).trimEnd()}${TRUNCATION_NOTICE}`;
}

export function prComment(summary: string, jobId?: string, sourceUrl?: string | null): string {
  const marker = jobId ? `<!-- sindral:job:${jobId} -->` : SINDRAL_MARKER;
  return [marker, summary.trim() || '_No summary provided._', ...(sourceUrl ? ['', `In response to ${sourceUrl}`] : [])].join('\n');
}

export function commitMessage(taskKey: string, summary: string): string {
  const firstLine = summary
    .split('\n')
    .map((l) => l.trim())
    .find((l) => l.length > 0);
  const subject = `${taskKey}: ${firstLine ?? 'update'}`.slice(0, 120);
  return subject;
}

function fail(what: string, result: RunResult): never {
  const detail = result.stderr.trim() || result.stdout.trim() || result.message;
  throw new Error(`${what} failed (exit ${result.exitCode ?? result.code ?? '?'}): ${detail}`);
}

/** Commits any uncommitted work (agents are asked to commit, but do not always) and pushes the branch. */
export async function commitAndPush(
  git: GitRunner,
  opts: { taskKey: string; summary: string; branch: string; baseBranch: string },
): Promise<{ committed: boolean }> {
  const status = await git(['status', '--porcelain']);
  let committed = false;
  if (status.stdout.trim()) {
    await git(['add', '-A']);
    await git(['-c', 'user.name=Sindral AI', '-c', 'user.email=sindral@users.noreply.github.com', 'commit', '--no-verify', `--author=${COMMIT_AUTHOR}`, '-m', commitMessage(opts.taskKey, opts.summary)]);
    committed = true;
  }
  await git(['fetch', '--prune', 'origin']);
  const rebase = await git.try([
    '-c', 'user.name=Sindral AI',
    '-c', 'user.email=sindral@users.noreply.github.com',
    'rebase', `origin/${opts.baseBranch}`,
  ]);
  if (rebase.failed || rebase.exitCode !== 0) {
    await git.try(['rebase', '--abort']);
    fail(`rebase onto ${opts.baseBranch}`, rebase);
  }
  await git(['push', '--force-with-lease', '-u', 'origin', `${opts.branch}:${opts.branch}`]);
  return { committed };
}

export interface EnsurePrOptions {
  gh: GhRunner;
  cwd: string;
  repo: RepoRef;
  branch: string;
  baseBranch: string;
  taskKey: string;
  taskTitle: string;
  motivation?: string;
  assumptions?: string;
  summary: string;
  jobId?: string;
  githubFeedback?: GitHubFeedbackReference;
}

export interface EnsurePrResult {
  url: string;
  created: boolean;
}

export async function findOpenPr(gh: GhRunner, cwd: string, repo: RepoRef, branch: string): Promise<string | null> {
  const list = await gh(['pr', 'list', '--repo', repo.full, '--head', branch, '--state', 'open', '--json', 'url', '--limit', '1'], { cwd });
  if (list.failed || list.exitCode !== 0) fail('gh pr list', list);
  try {
    const parsed = JSON.parse(list.stdout || '[]') as { url?: unknown }[];
    const url = parsed[0]?.url;
    return typeof url === 'string' && url.length > 0 ? url : null;
  } catch {
    throw new Error(`gh pr list returned unexpected output: ${list.stdout.slice(0, 200)}`);
  }
}

/**
 * Opens a PR for the branch, or comments on the existing one so reviewers on
 * GitHub see the agent's response to their feedback.
 */
export async function ensurePr(opts: EnsurePrOptions): Promise<EnsurePrResult> {
  const existing = await findOpenPr(opts.gh, opts.cwd, opts.repo, opts.branch);
  if (existing) {
    await postPrUpdate(opts, existing);
    return { url: existing, created: false };
  }
  const created = await opts.gh(
    [
      'pr',
      'create',
      '--repo',
      opts.repo.full,
      '--head',
      opts.branch,
      '--base',
      opts.baseBranch,
      '--title',
      prTitle(opts.taskKey, opts.taskTitle),
      '--body',
      prBody({ taskKey: opts.taskKey, motivation: opts.motivation, assumptions: opts.assumptions, summary: opts.summary }),
    ],
    { cwd: opts.cwd },
  );
  if (created.failed || created.exitCode !== 0) fail('gh pr create', created);
  const url = extractPrUrl(created.stdout);
  if (!url) {
    // gh prints the URL last; if the output format changes, fall back to a lookup.
    const found = await findOpenPr(opts.gh, opts.cwd, opts.repo, opts.branch);
    if (!found) throw new Error(`gh pr create succeeded but no PR URL was found in output: ${created.stdout.slice(0, 200)}`);
    return { url: found, created: true };
  }
  return { url, created: true };
}

async function postPrUpdate(opts: EnsurePrOptions, prUrl: string): Promise<void> {
  const number = Number(/\/pull\/(\d+)(?:$|[?#])/.exec(prUrl)?.[1]);
  if (!Number.isInteger(number) || number <= 0) throw new Error(`Pull request URL has no valid number: ${prUrl}`);
  const marker = opts.jobId ? `<!-- sindral:job:${opts.jobId} -->` : SINDRAL_MARKER;
  const directReply = opts.githubFeedback?.kind === 'review_comment' && opts.githubFeedback.prUrl === prUrl;
  const listPath = directReply
    ? `repos/${opts.repo.full}/pulls/${number}/comments`
    : `repos/${opts.repo.full}/issues/${number}/comments`;
  if (opts.jobId) {
    const existing = await opts.gh(['api', listPath, '--paginate', '--jq', `.[] | select(.body | contains("${marker}")) | .id`], { cwd: opts.cwd });
    if (existing.failed || existing.exitCode !== 0) fail('gh api comment lookup', existing);
    if (existing.stdout.trim()) return;
  }
  const body = prComment(opts.summary, opts.jobId, opts.githubFeedback?.commentUrl);
  if (directReply) {
    const reply = await opts.gh(
      ['api', '--method', 'POST', `repos/${opts.repo.full}/pulls/${number}/comments/${opts.githubFeedback!.commentId}/replies`, '-f', `body=${body}`],
      { cwd: opts.cwd },
    );
    if (reply.failed || reply.exitCode !== 0) fail('gh api review comment reply', reply);
    return;
  }
  const comment = await opts.gh(['pr', 'comment', prUrl, '--repo', opts.repo.full, '--body', body], { cwd: opts.cwd });
  if (comment.failed || comment.exitCode !== 0) fail('gh pr comment', comment);
}

export function extractPrUrl(output: string): string | null {
  const match = /https:\/\/github\.com\/[^\s/]+\/[^\s/]+\/pull\/\d+/.exec(output);
  return match ? match[0] : null;
}
