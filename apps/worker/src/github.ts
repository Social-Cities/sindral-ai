import type { GitRunner } from './git.js';
import { run, type RunOptions, type RunResult } from './proc.js';
import type { RepoRef } from './workspace.js';

/** Marker embedded in PR bodies/comments so the server can recognise Sindral's own posts. */
export const SINDRAL_MARKER = '<!-- sindral -->';
export const COMMIT_AUTHOR = 'Sindral AI <sindral@users.noreply.github.com>';

export type GhRunner = (args: readonly string[], opts?: RunOptions) => Promise<RunResult>;

/** Builds a `gh` invoker; the token is passed only to `gh` through `GH_TOKEN`. */
export function ghRunner(ghBin: string, token: string | null): GhRunner {
  return (args, opts = {}) =>
    run(ghBin, args, {
      ...opts,
      env: { GH_PROMPT_DISABLED: '1', GH_NO_UPDATE_NOTIFIER: '1', ...(token ? { GH_TOKEN: token } : {}), ...opts.env },
    });
}

export function prTitle(taskKey: string, taskTitle: string): string {
  const title = taskTitle.trim() || 'Sindral change';
  return `${taskKey}: ${title}`.slice(0, 250);
}

export function prBody(opts: { taskKey: string; summary: string; taskUrl?: string }): string {
  return [
    '## Summary',
    '',
    opts.summary.trim() || '_No summary provided._',
    '',
    `Task ${opts.taskKey}${opts.taskUrl ? ` (${opts.taskUrl})` : ''}`,
    '',
    'Generated by Sindral AI. Comments on this pull request are picked up as feedback.',
    '',
    SINDRAL_MARKER,
  ].join('\n');
}

export function prComment(summary: string): string {
  return `${SINDRAL_MARKER}\n${summary.trim() || '_No summary provided._'}`;
}

export function commitMessage(taskKey: string, summary: string): string {
  const firstLine = summary
    .split('\n')
    .map((l) => l.trim())
    .find((l) => l.length > 0);
  const subject = `${taskKey}: ${firstLine ?? 'update'}`.slice(0, 120);
  return subject;
}

function fail(what: string, result: RunResult): never {
  const detail = result.stderr.trim() || result.stdout.trim() || result.message;
  throw new Error(`${what} failed (exit ${result.exitCode ?? result.code ?? '?'}): ${detail}`);
}

/** Commits any uncommitted work (agents are asked to commit, but do not always) and pushes the branch. */
export async function commitAndPush(git: GitRunner, opts: { taskKey: string; summary: string; branch: string }): Promise<{ committed: boolean }> {
  const status = await git(['status', '--porcelain']);
  let committed = false;
  if (status.stdout.trim()) {
    await git(['add', '-A']);
    await git(['-c', 'user.name=Sindral AI', '-c', 'user.email=sindral@users.noreply.github.com', 'commit', '--no-verify', `--author=${COMMIT_AUTHOR}`, '-m', commitMessage(opts.taskKey, opts.summary)]);
    committed = true;
  }
  await git(['push', '--force-with-lease', '-u', 'origin', `${opts.branch}:${opts.branch}`]);
  return { committed };
}

export interface EnsurePrOptions {
  gh: GhRunner;
  cwd: string;
  repo: RepoRef;
  branch: string;
  baseBranch: string;
  taskKey: string;
  taskTitle: string;
  summary: string;
}

export interface EnsurePrResult {
  url: string;
  created: boolean;
}

export async function findOpenPr(gh: GhRunner, cwd: string, repo: RepoRef, branch: string): Promise<string | null> {
  const list = await gh(['pr', 'list', '--repo', repo.full, '--head', branch, '--state', 'open', '--json', 'url', '--limit', '1'], { cwd });
  if (list.failed || list.exitCode !== 0) fail('gh pr list', list);
  try {
    const parsed = JSON.parse(list.stdout || '[]') as { url?: unknown }[];
    const url = parsed[0]?.url;
    return typeof url === 'string' && url.length > 0 ? url : null;
  } catch {
    throw new Error(`gh pr list returned unexpected output: ${list.stdout.slice(0, 200)}`);
  }
}

/**
 * Opens a PR for the branch, or comments on the existing one so reviewers on
 * GitHub see the agent's response to their feedback.
 */
export async function ensurePr(opts: EnsurePrOptions): Promise<EnsurePrResult> {
  const existing = await findOpenPr(opts.gh, opts.cwd, opts.repo, opts.branch);
  if (existing) {
    const comment = await opts.gh(['pr', 'comment', existing, '--repo', opts.repo.full, '--body', prComment(opts.summary)], { cwd: opts.cwd });
    if (comment.failed || comment.exitCode !== 0) fail('gh pr comment', comment);
    return { url: existing, created: false };
  }
  const created = await opts.gh(
    [
      'pr',
      'create',
      '--repo',
      opts.repo.full,
      '--head',
      opts.branch,
      '--base',
      opts.baseBranch,
      '--title',
      prTitle(opts.taskKey, opts.taskTitle),
      '--body',
      prBody({ taskKey: opts.taskKey, summary: opts.summary }),
    ],
    { cwd: opts.cwd },
  );
  if (created.failed || created.exitCode !== 0) fail('gh pr create', created);
  const url = extractPrUrl(created.stdout);
  if (!url) {
    // gh prints the URL last; if the output format changes, fall back to a lookup.
    const found = await findOpenPr(opts.gh, opts.cwd, opts.repo, opts.branch);
    if (!found) throw new Error(`gh pr create succeeded but no PR URL was found in output: ${created.stdout.slice(0, 200)}`);
    return { url: found, created: true };
  }
  return { url, created: true };
}

export function extractPrUrl(output: string): string | null {
  const match = /https:\/\/github\.com\/[^\s/]+\/[^\s/]+\/pull\/\d+/.exec(output);
  return match ? match[0] : null;
}
